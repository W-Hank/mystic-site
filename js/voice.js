  function orderOf(len, seedNum) {
    const a = [];
    for (let i = 0; i < len; i++) a.push(i);
    let st = mix(seedNum | 0) || 1;
    for (let i = len - 1; i > 0; i--) {
      st = mix(st + i);
      const j = st % (i + 1);
      const t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }

  function pick(arr, n) {
    if (!arr || !arr.length) return "";
    const len = arr.length;
    /* 固定但打乱的顺序：周期内不重复、不连撞，顺序本身不可预测 */
    const perm = orderOf(len, n | 0);
    const day = dayNumber();
    const pos = ((day % len) + len) % len;
    const base = arr[perm[pos]];
    const alt = ALT[base];
    if (alt && Math.floor(day / len) % 2 === 1) return alt;
    return base;
  }

  function dayKey() {
    const d = new Date();
    return d.getFullYear() + "-" + (d.getMonth() + 1) + "-" + d.getDate();
  }

  /* 连续两天必定换一种说法：下标随日期 +1，不会和前一天撞同一句 */
  function dayNumber() {
    const d = new Date();
    return Math.floor(new Date(d.getFullYear(), d.getMonth(), d.getDate()).getTime() / 86400000);
  }

